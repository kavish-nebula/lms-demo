import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { WORKFLOW_KINDS,WorkflowSchema,WorkflowSaveSchema,checkWorkflow,type Workflow } from "../../src/lib/workflow-project";
import { workflowOf,saveWorkflow } from "../../src/server/workflow-project";
import { getSessionUser } from "../../src/server/auth";
import { db } from "../../src/server/db/client";
import { users,enrollments,projectWork,stepProgress,signals } from "../../src/server/db/schema";
import { eq } from "drizzle-orm";
import { GET,PUT } from "../../src/app/api/v1/enrollments/[courseId]/workflow-project/route";
import { POST } from "../../src/app/api/v1/enrollments/[courseId]/workflow-project/check/route";

const nodes = WORKFLOW_KINDS.map((kind,i) => ({ id: randomUUID(),kind,label: kind,notes: "",position: { x: i*250,y: 100 } }));
const id = (kind: string) => nodes.find((n) => n.kind === kind)!.id;
const edge = (from: string,to: string,branch: Workflow["edges"][number]["branch"] = "next") => ({ id: randomUUID(),source: id(from),target: id(to),branch });
const graph: Workflow = { version: 1,nodes,edges: [edge("receive","guard"),edge("guard","classify","allowed"),edge("guard","handoff","blocked"),edge("classify","lookup"),edge("lookup","decide"),edge("decide","reply","found"),edge("decide","handoff","missing")] };
assert.equal(WorkflowSchema.safeParse(graph).success,true);
assert.equal(checkWorkflow(graph).passed,true,"Safe architecture passes all scenarios");
assert.equal(checkWorkflow({ ...graph,edges: [] }).passed,false);
assert.equal(checkWorkflow({ ...graph,edges: graph.edges.filter((e) => e.branch !== "missing") }).checks.find((c) => c.id === "branches")!.passed,false);
const bypass = { ...graph,edges: graph.edges.map((e) => e.source===id("receive") ? { ...e,target:id("classify") } : e) };
assert.equal(checkWorkflow(bypass).checks.find((c) => c.id === "safe")!.passed,false,"Tool routes require safety");
const unsafe = { ...graph,edges: graph.edges.map((e) => e.branch === "blocked" ? { ...e,target:id("lookup") } : e) };
assert.equal(checkWorkflow(unsafe).checks.find((c) => c.id === "safe")!.passed,false);
const loop = { ...graph,edges: graph.edges.map((e) => e.source === id("lookup") ? { ...e,target:id("classify") } : e) };
assert.equal(checkWorkflow(loop).checks.find((c) => c.id === "terminates")!.passed,false,"Cycles terminate validation safely");
const wrongOrder = { ...graph,edges: [edge("receive","guard"),edge("guard","lookup","allowed"),edge("guard","handoff","blocked"),edge("lookup","classify"),edge("classify","decide"),edge("decide","reply","found"),edge("decide","handoff","missing")] };
assert.equal(checkWorkflow(wrongOrder).checks.find((c) => c.id === "order")!.passed,false,"Classification precedes lookup");
assert.equal(WorkflowSchema.safeParse({ ...graph,nodes:[...nodes,nodes[0]] }).success,false);
assert.equal(WorkflowSchema.safeParse({ ...graph,edges:[...graph.edges,edge("guard","reply","allowed")] }).success,false);
assert.equal(WorkflowSchema.safeParse({ ...graph,edges:[{ ...graph.edges[0],target:randomUUID() }] }).success,false);
assert.equal(WorkflowSaveSchema.safeParse({ diagram:graph,revision:0,passed:true }).success,false,"Clients cannot submit grades");
assert.equal(WorkflowSchema.safeParse({ ...graph,nodes: nodes.map((n) => ({ ...n,notes:"x".repeat(501) })) }).success,false);

const user = await getSessionUser(); const d = await db();
const [e] = await d.insert(enrollments).values({ userId:user.id,courseId:"ai-agent",answers:{} }).returning();
await d.insert(projectWork).values({ enrollmentId:e.id,files:{ "prompt_engine.py":"keep existing Python" } });
const initial = await workflowOf(user,"ai-agent"); assert.equal(initial.revision,0);
const saved = await saveWorkflow(user,"ai-agent",graph,0,true);
assert.equal(saved.report!.passed,true);
assert.equal((await workflowOf(user,"ai-agent")).revision,1);
const writes = await Promise.allSettled([saveWorkflow(user,"ai-agent",graph,1),saveWorkflow(user,"ai-agent",graph,1)]);
assert.equal(writes.filter((x) => x.status === "fulfilled").length,1,"Concurrent stale saves cannot overwrite");
assert.equal((await workflowOf(user,"ai-agent")).report,null,"New save clears obsolete check report");
assert.equal((await d.query.projectWork.findFirst({ where:eq(projectWork.enrollmentId,e.id) }))!.files["prompt_engine.py"],"keep existing Python");
assert.equal((await d.select().from(stepProgress)).length,0,"Diagram checks never mark course stages complete");
assert.equal((await d.select().from(signals)).length,0,"Diagram checks never change adaptation");
const stranger = { ...user,id:"other-user" }; await d.insert(users).values({ id:stranger.id,name:"Other",email:"other@example.test" });
await assert.rejects(workflowOf(stranger,"ai-agent"));
await assert.rejects(saveWorkflow(user,"unknown",graph,0));
const ctx = { params:Promise.resolve({ courseId:"ai-agent" }) };
const req = (input:unknown) => new Request("http://localhost/api",{ method:"PUT",headers:{"content-type":"application/json"},body:JSON.stringify(input) });
assert.equal((await GET(new Request("http://localhost/api"),ctx)).status,200);
assert.equal((await PUT(req({ diagram:graph,revision:0 }),ctx)).status,409);
assert.equal((await PUT(req({ diagram:graph,revision:2,points:50 }),ctx)).status,400);
assert.equal((await POST(req({ diagram:graph,revision:2 }),ctx)).status,200);
await d.delete(enrollments).where(eq(enrollments.id,e.id));
assert.equal((await d.query.workflowProjects.findMany()).length,0,"Enrollment/reset deletion cascades to drawing projects");
console.log("Workflow tests passed: architecture paths, safety, ordering, validation, persistence, isolation, concurrency, Python preservation and reset.");
process.exit(0);
