const draftA = { log: { id: "tab-a" }, waiting: true };
const draftB = { log: { id: "tab-b" }, waiting: true };
const draftStorage = new Map<string,string>();
function applyDrafts(before: typeof draftA[], after: typeof draftA[]) {
  for (const { id,value } of draftChanges(before,after)) if (value === null) draftStorage.delete(id); else draftStorage.set(id,value);
}
applyDrafts([], [draftA]); applyDrafts([], [draftB]);
assert.equal(draftStorage.size,2,"Concurrent tabs retain independent offline drafts");
applyDrafts([draftA], []);
assert.ok(draftStorage.has("tab-b"),"Syncing one tab does not discard another tab's draft");
applyDrafts([draftA,draftB], [draftA,{ ...draftB,waiting: false }]);
assert.ok(!draftStorage.has("tab-a"),"A stale tab does not resurrect an unchanged synced draft");

